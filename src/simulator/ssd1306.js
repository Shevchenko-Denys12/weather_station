export const GLYPH_W = 6
export const GLYPH_H = 8

export function createFrame() {
  const px = new Uint8Array(WIDTH * HEIGHT) // 1 byte per pixel, row-major
  let cx = 0
  let cy = 0

  const pixel = (x, y, on = 1) => {
    if (x >= 0 && x < WIDTH && y >= 0 && y < HEIGHT) px[y * WIDTH + x] = on ? 1 : 0
  }

  const glyph = (ch) => {
    const code = ch.charCodeAt(0)
    const g = FONT[code - 0x20] ?? FONT['?'.charCodeAt(0) - 0x20]
    for (let col = 0; col < 5; col++) {
      for (let row = 0; row < 7; row++) pixel(cx + col, cy + row, (g[col] >> row) & 1)
    }
    cx += GLYPH_W
  }

  return {
    fill: (on = 0) => px.fill(on ? 1 : 0),
    setCursor(x, y) {
      cx = x
      cy = y
    },
    pixel,
    writeString(text) {
      for (const ch of text) glyph(ch)
    },
    /** Bresenham line, both ends included. */
    line(x0, y0, x1, y1) {
      const dx = Math.abs(x1 - x0)
      const dy = -Math.abs(y1 - y0)
      const sx = x0 < x1 ? 1 : -1
      const sy = y0 < y1 ? 1 : -1
      let err = dx + dy
      for (;;) {
        pixel(x0, y0)
        if (x0 === x1 && y0 === y1) break
        const e2 = 2 * err
        if (e2 >= dy) {
          err += dy
          x0 += sx
        }
        if (e2 <= dx) {
          err += dx
          y0 += sy
        }
      }
    },
    snapshot: () => px.slice(),
  }
}
